"""Real host UI acceptance. GitHub transport and connector are explicitly isolated fixtures."""
import json, sys
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

root=Path(sys.argv[1]);info=json.loads((root/'browser.json').read_text());out=root/'screenshots';out.mkdir(exist_ok=True)
checks=[];errors=[]
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    context=browser.new_context(viewport={'width':1440,'height':1000})
    name,value=info['cookie'].split('=',1);context.add_cookies([{'name':name,'value':value,'url':info['base']}])
    page=context.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
    try:
        page.goto(info['url']);page.wait_for_load_state('networkidle')
        expect(page.get_by_role('heading',name='Plugins & tools',exact=True)).to_be_visible()
        page.screenshot(path=str(out/'market-light.png'))
        page.get_by_role('button',name='Switch to dark mode',exact=True).click();page.wait_for_timeout(220)
        page.screenshot(path=str(out/'market-dark.png'))
        search=page.get_by_role('textbox',name='Search plugins');search.fill('NO_SUCH_PLUGIN')
        expect(page.get_by_role('heading',name='No matching plugins')).to_be_visible();expect(search).to_be_focused();search.fill('')
        page.get_by_role('combobox',name='Plugin category').select_option('workspace-view')
        expect(page.locator('.market-card')).to_have_count(2)
        page.get_by_role('combobox',name='Plugin category').select_option('all')
        checks.append('shared shell, white/dark themes, search empty state and category filter')

        card=page.locator('.market-card').filter(has_text='Roppo acceptance').filter(has=page.get_by_role('heading',name='Agent board',exact=True))
        button=card.get_by_role('button',name='Agent board',exact=True);button.click()
        drawer=page.get_by_role('dialog');expect(drawer).to_be_visible()
        drawer.get_by_role('combobox',name='Version',exact=True).select_option('1.0.0')
        drawer.get_by_role('button',name='Install plugin',exact=True).click()
        expect(drawer.get_by_role('heading',name='Review changes')).to_be_visible()
        expect(drawer.get_by_role('button',name='Confirm install',exact=True)).to_be_enabled()
        expect(drawer).to_contain_text('Read team activity, tasks and usage')
        drawer.locator('.market-review').scroll_into_view_if_needed()
        primary=drawer.get_by_role('button',name='Confirm install',exact=True);primary.hover()
        assert primary.evaluate('(e)=>getComputedStyle(e).backgroundColor')=='rgb(245, 245, 245)'
        page.screenshot(path=str(out/'install-review-dark.png'))
        drawer.get_by_role('button',name='Confirm install',exact=True).click()
        expect(drawer.get_by_role('link',name='Open',exact=True)).to_be_visible(timeout=15000)
        drawer.get_by_role('link',name='Open',exact=True).click()
        frame=page.frame_locator('iframe[title="Agent board"]');expect(frame.get_by_role('heading',name='Agent board',exact=True)).to_be_visible()
        assert page.url.endswith('#plugin/agent-board')
        page.locator('iframe[title="Agent board"]').screenshot(path=str(out/'board-preview.png'))
        page.goto(info['url']);page.wait_for_load_state('networkidle')
        unpublished=page.locator('.market-card').filter(has_text='pythc').filter(has=page.get_by_role('heading',name='Agent board',exact=True))
        unpublished.get_by_role('button',name='Agent board',exact=True).click();drawer=page.get_by_role('dialog')
        expect(drawer).to_contain_text('No installation package has been published yet.')
        expect(drawer.get_by_role('link',name='Open',exact=True)).to_have_count(0)
        expect(drawer.get_by_role('button',name='Uninstall',exact=True)).to_have_count(0)
        page.screenshot(path=str(out/'other-source-details-dark.png'))
        drawer.get_by_role('button',name='Close / 关闭').click()
        checks.append('review permissions, real archive install, live sandboxed board, and source-bound installed details')

        page.goto(info['base']+'/configure#integrations/updates');page.wait_for_load_state('networkidle')
        row=page.locator('.market-installed article').filter(has_text='Agent board');expect(row).to_contain_text('1.0.0 → 1.1.0')
        row.get_by_role('button',name='Review update',exact=True).click()
        drawer=page.get_by_role('dialog');drawer.get_by_role('button',name='Update',exact=True).click();drawer.get_by_role('button',name='Confirm install',exact=True).click()
        expect(drawer.locator('.market-current')).to_contain_text('1.1.0')
        drawer.get_by_role('button',name='Roll back to 1.0.0',exact=True).click();drawer.get_by_role('button',name='Confirm roll back',exact=True).click()
        expect(drawer.locator('.market-current')).to_contain_text('1.0.0')
        drawer.get_by_role('button',name='Disable plugin',exact=True).click();drawer.get_by_role('button',name='Confirm disable',exact=True).click()
        expect(drawer.locator('.market-current')).to_contain_text('Disabled')
        drawer.get_by_role('button',name='Enable plugin',exact=True).click();drawer.get_by_role('button',name='Confirm enable',exact=True).click()
        expect(drawer.locator('.market-current')).to_contain_text('Enabled')
        page.screenshot(path=str(out/'installed-details-dark.png'))
        drawer.get_by_role('button',name='Close / 关闭').press('Escape');expect(drawer).not_to_be_visible()
        expect(row.get_by_role('button',name='Review update',exact=True)).to_be_focused()
        checks.append('compatible update, rollback, disable/enable, Escape dismissal and focus restoration')

        page.goto(info['url']);page.wait_for_load_state('networkidle')
        card=page.locator('.market-card').filter(has=page.get_by_role('heading',name='Test connector',exact=True))
        card.get_by_role('button',name='Test connector',exact=True).click();drawer=page.get_by_role('dialog')
        drawer.get_by_role('button',name='Install plugin',exact=True).click();drawer.get_by_role('button',name='Confirm install',exact=True).click()
        expect(drawer.get_by_role('button',name='Enable version 1.0.0',exact=True)).to_be_visible()
        # Exercise a changing blocker snapshot; backend regression separately checks real unfinished records.
        waiting=[True]
        def blockers(route):
            response=route.fetch();data=response.json();data['blockers']=[{'kind':'tasks','count':1}] if waiting[0] else [];route.fulfill(response=response,json=data)
        page.route('**/api/plugin-market',blockers)
        drawer.get_by_role('button',name='Enable version 1.0.0',exact=True).click();expect(drawer).to_contain_text('restarts the host')
        expect(drawer.get_by_role('button',name='Confirm activate',exact=True)).to_be_disabled()
        expect(drawer.get_by_role('button',name='Recheck availability',exact=True)).to_be_enabled()
        drawer.locator('.market-review').scroll_into_view_if_needed()
        page.screenshot(path=str(out/'activation-blocked-dark.png'))
        waiting[0]=False
        expect(drawer.get_by_role('button',name='Confirm activate',exact=True)).to_be_enabled(timeout=10000)
        page.screenshot(path=str(out/'activation-ready-dark.png'))
        page.unroute('**/api/plugin-market',blockers)
        drawer.get_by_role('button',name='Confirm activate',exact=True).click();expect(drawer.get_by_role('button',name='Add connection',exact=True)).to_be_visible(timeout=15000)
        drawer.get_by_role('button',name='Add connection',exact=True).click();drawer=page.get_by_role('dialog')
        drawer.get_by_label('Connection name',exact=True).fill('Acceptance connection')
        drawer.get_by_label('Allowed sender IDs',exact=True).fill('operator')
        drawer.get_by_label('channels *',exact=True).fill('acceptance-room')
        drawer.get_by_role('button',name='Review connection',exact=True).click()
        expect(drawer.get_by_role('button',name='Apply connection',exact=True)).to_be_enabled()
        page.screenshot(path=str(out/'connection-review-dark.png'))
        drawer.get_by_role('button',name='Apply connection',exact=True).click();expect(page.get_by_role('dialog')).not_to_be_visible(timeout=15000)
        page.get_by_role('link',name='Installed',exact=True).click()
        row=page.locator('.market-installed article').filter(has_text='Test connector');expect(row).to_contain_text('1 connections')
        row.get_by_role('button',name='Manage',exact=True).click();drawer=page.get_by_role('dialog')
        expect(drawer.get_by_role('button',name='Uninstall',exact=True)).to_be_disabled();expect(drawer).to_contain_text('Acceptance connection')
        drawer.get_by_role('button',name='Close / 关闭').click()
        checks.append('source staged versus activated, changing blockers recover, controlled restart, scoped connection and uninstall guard')

        page.get_by_role('link',name='Tool connections',exact=True).click()
        expect(page.locator('.management-content')).to_be_visible();expect(page.get_by_role('navigation',name='Plugin sections')).to_be_visible()
        page.get_by_role('link',name='Marketplace',exact=True).click()
        page.get_by_role('button',name='Manage sources',exact=True).click();drawer=page.get_by_role('dialog')
        drawer.get_by_label('GitHub repository or directory',exact=True).fill('https://github.com/acme/missing')
        drawer.get_by_role('button',name='Add source',exact=True).click()
        expect(drawer.locator('.market-source').filter(has_text='acme/missing')).to_contain_text('not found or private')
        expect(drawer.locator('.market-source').filter(has_text='acme/missing').get_by_role('button',name='Refresh',exact=True)).to_be_enabled()
        page.screenshot(path=str(out/'source-error-dark.png'))
        drawer.get_by_role('button',name='Close / 关闭').click()
        checks.append('legacy tool settings retained, source management and recoverable GitHub failure')

        page.get_by_role('button',name='Switch to Chinese',exact=True).click()
        page.emulate_media(reduced_motion='reduce');page.set_viewport_size({'width':390,'height':844})
        expect(page.get_by_role('heading',name='插件与工具',exact=True)).to_be_visible()
        assert page.locator('html').evaluate('(e)=>e.scrollWidth<=e.clientWidth+1')
        page.screenshot(path=str(out/'market-mobile-dark.png'))
        page.get_by_role('button',name='管理来源',exact=True).click();drawer=page.get_by_role('dialog')
        assert drawer.evaluate('(e)=>e.scrollWidth<=e.clientWidth+1')
        assert drawer.evaluate('(e)=>getComputedStyle(e).animationName')=='none'
        page.screenshot(path=str(out/'source-mobile-dark.png'))
        drawer.get_by_role('button',name='Close / 关闭').press('Escape')
        page.get_by_role('button',name='切换为浅色模式',exact=True).click()
        page.screenshot(path=str(out/'market-mobile-light.png'))
        checks.append('390px Chinese white/dark, no horizontal overflow and reduced-motion drawer')
        assert not errors,errors
    finally:
        (root/'browser-report.json').write_text(json.dumps({'checks':checks,'pageErrors':errors},ensure_ascii=False,indent=2))
        browser.close()
print(json.dumps({'checks':checks,'pageErrors':errors},ensure_ascii=False))
