"""Personality, private memories and method controls against an isolated real host."""
import json
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect, TimeoutError
root=Path(os.environ['MEMORY_BROWSER_DIR'])
f=json.loads((root/'fixture.json').read_text())
checks=[];errors=[]
def check(text):
    checks.append(text);print('PASS '+text,flush=True)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    context=browser.new_context(viewport={'width':1440,'height':1000},reduced_motion='reduce')
    name,value=f['cookie'].split('=',1)
    context.add_cookies([{'name':name,'value':value,'url':f['url']}])
    context.add_init_script("localStorage.setItem('agenthub.configuration.language','zh-CN');localStorage.setItem('agenthub.configuration.theme','light')")
    page=context.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
    def navigate(path):
        page.goto(f['url']+path)
        # The workspace keeps a streaming connection/polling alive. Try idle,
        # then wait for the specific interactive surface below.
        try:page.wait_for_load_state('networkidle',timeout=2000)
        except TimeoutError:pass
    def workspace():return context.request.get(f['url']+'/api/chat/memory').json()['contexts']
    def private():return next(c for c in workspace() if c.get('conversationId')==f['chat'])
    navigate('/configure#advanced/memory')
    memory=page.get_by_role('region',name='记忆',exact=True)
    expect(memory).to_be_visible()
    source=memory.get_by_role('combobox',name='记忆来源')
    source.select_option(private()['id'])
    assert '另一个账号' not in source.inner_text()
    expect(memory.locator('.memory-note:visible')).to_have_count(2)
    check('personal Chat is listed through the owner API; another account is absent')
    note=memory.locator('[data-memory-id="'+f['chatPreference']+'"]')
    expect(note.get_by_text('建议替换原有记忆',exact=True)).to_have_count(0)
    note.get_by_role('button',name='来源与历史').click()
    expect(note.locator('blockquote')).to_contain_text('技术报告先给结论')
    note.get_by_role('button',name='收起来源').click()
    note.get_by_role('button',name='修改',exact=True).click()
    note.get_by_role('textbox',name='记忆内容',exact=True).fill('不保存的修改')
    note.get_by_role('button',name='取消',exact=True).click()
    expect(note.get_by_role('button',name='修改',exact=True)).to_be_focused()
    note.get_by_role('button',name='修改',exact=True).click()
    note.get_by_role('textbox',name='记忆内容',exact=True).fill('技术报告先列验证结果')
    note.get_by_role('textbox',name='适用情况',exact=True).fill('代码审查报告')
    note.get_by_role('button',name='保存',exact=True).click()
    expect(note.locator('.memory-content')).to_have_text('技术报告先列验证结果')
    assert next(x for x in private()['items'] if x['id']==f['chatPreference'])['learning']['condition']=='代码审查报告'
    check('source inspection, cancellation focus, content and applicability editing work')
    memory.locator('summary').filter(has_text='待确认的记忆').click()
    candidate=memory.locator('[data-memory-id="'+f['chatCandidate']+'"]')
    candidate.get_by_role('button',name='采纳',exact=True).click()
    expect(memory.locator('.memory-note:visible')).to_have_count(3)
    memory.locator('summary').filter(has_text='整理与导出').click()
    memory.get_by_label('导入记忆文件',exact=True).set_input_files({'name':'USER.md','mimeType':'text/markdown','buffer':b'# USER.md\n\n- Browser imported preference'})
    imported=memory.locator('.memory-note').filter(has_text='Browser imported preference')
    expect(imported.get_by_role('button',name='忽略')).to_be_visible()
    imported.get_by_role('button',name='忽略').click();expect(imported).to_have_count(0)
    expect(note).to_be_visible()
    with page.expect_download() as dl:memory.get_by_role('button',name='USER.md',exact=True).click()
    text=Path(dl.value.path()).read_text();assert '技术报告先列验证结果' in text;assert 'Browser imported preference' not in text
    check('candidate acceptance, file import, dismissal and export preserve active notes')
    toggle=memory.get_by_role('checkbox',name='从交流中学习')
    toggle.check();expect(toggle).to_be_checked()
    page.wait_for_function("async()=>{let x=await(await fetch('/api/chat/memory')).json();return x.contexts.some(c=>c.policy.writeMode==='adaptive')}")
    toggle.uncheck();expect(toggle).not_to_be_checked()
    page.wait_for_function("async(id)=>{let x=await(await fetch('/api/chat/memory')).json();return x.contexts.find(c=>c.id===id).policy.writeMode==='explicit_only'}",arg=private()['id'])
    check('automatic learning can be enabled and paused without deleting notes')
    memory.locator('summary').filter(has_text='工作方法').click()
    memory.get_by_role('button',name='保存为方法',exact=True).click()
    memory.get_by_role('button',name='保存方法',exact=True).click()
    expect(memory.locator('.memory-method').filter(has_text='演示报告方法')).to_be_visible()
    method=memory.locator('.memory-method').filter(has_text='演示报告方法')
    method.get_by_role('button',name='编辑或恢复此版').click()
    memory.get_by_role('textbox',name='方法名称',exact=True).fill('参数化报告')
    memory.get_by_role('textbox',name='目标',exact=True).fill('生成 {{file}} 报告')
    memory.get_by_role('textbox',name='输入参数：每行填写 name = 名称').fill('file = 文件名称')
    memory.get_by_role('button',name='保存方法',exact=True).click()
    edited=memory.locator('.memory-method').filter(has_text='参数化报告')
    expect(edited).to_contain_text('待试用')
    edited.get_by_role('button',name='运行 / 试用').click()
    memory.get_by_role('textbox',name='文件名称',exact=True).fill('weekly.md')
    memory.get_by_role('button',name='启动实际任务',exact=True).click()
    expect(memory.get_by_text('任务已启动，可在任务页查看进展。',exact=True)).to_be_visible()
    edited.get_by_role('button',name='停用',exact=True).click();expect(edited).to_contain_text('已停用')
    method.get_by_role('button',name='编辑或恢复此版').click()
    memory.get_by_role('button',name='保存方法',exact=True).click()
    expect(memory.locator('.memory-method').filter(has_text='v3')).to_be_visible()
    check('methods support saving, parameter editing, explicit trial, retirement and restoring as a new version')
    while memory.locator('details[open] > summary').count():memory.locator('details[open] > summary').first.click()
    page.screenshot(path=str(root/'memory-light.png'),full_page=True)
    page.get_by_role('button',name='切换为深色模式',exact=True).click()
    expect(page.locator('html')).to_have_attribute('data-theme','dark');page.screenshot(path=str(root/'memory-dark.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    expect(source).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth<=window.innerWidth+1')
    page.screenshot(path=str(root/'memory-mobile.png'),full_page=True)
    check('desktop, dark theme and mobile layouts fit the existing typography')
    page.set_viewport_size({'width':1440,'height':1000})
    navigate('/configure#execution/configuration')
    expect(page.locator('#team-persona-identity')).to_be_visible()
    page.locator('#team-persona-identity').fill('任务协调助手')
    page.locator('summary').filter(has_text='人格文件').click()
    page.locator('#team-persona-file').set_input_files({'name':'SOUL.md','mimeType':'text/markdown','buffer':'# SOUL.md\n\n简洁、坦诚、先核实事实'.encode()})
    expect(page.locator('#team-persona-soul')).to_have_value('简洁、坦诚、先核实事实')
    page.get_by_role('button',name='保存更改',exact=True).click()
    expect(page.get_by_role('button',name='保存更改',exact=True)).to_have_count(0)
    page.reload();expect(page.locator('#team-persona-soul')).to_have_value('简洁、坦诚、先核实事实')
    page.locator('summary').filter(has_text='人格文件').click()
    with page.expect_download() as dl:page.get_by_role('button',name='SOUL.md',exact=True).click()
    assert '简洁、坦诚、先核实事实' in Path(dl.value.path()).read_text()
    page.screenshot(path=str(root/'persona.png'),full_page=True)
    check('personality import is a saved draft and survives reload; export matches it')
    before_reset=context.request.get(f['url']+'/settings').json()['current']
    entry=private()
    assert context.request.post(f['url']+'/api/chat/memory',headers={'origin':f['url']},data={'entryId':entry['id'],'action':'learning','enabled':True,'revision':entry['revision']}).ok
    page.evaluate("""id=>{localStorage.setItem('roppo.chat.draft.'+id,'OLD RESET DRAFT');localStorage.setItem('roppo.resources.'+id,'OLD RESOURCE STATE');localStorage.setItem('roppo.chat.panel.'+id,'files');sessionStorage.setItem('roppo.website.'+id,'https://example.com/old') }""",f['chat'])
    navigate('/configure#advanced/chat')
    page.get_by_role('button',name='清空所有记忆和上下文',exact=True).click()
    expect(page.get_by_role('group',name='确认清空')).to_contain_text('手动设置的人格')
    page.get_by_role('button',name='确认清空',exact=True).click()
    expect(page.get_by_text('个人记忆已恢复到初始状态。',exact=True)).to_be_visible(timeout=15000)
    assert context.request.get(f['url']+'/settings').json()['current']==before_reset
    assert context.request.get(f['url']+'/api/chat/space').json()['conversation'] is None
    assert not any(c.get('conversationId') for c in workspace())
    assert context.request.get(f['url']+'/api/chat/conversations/'+f['chat']).status>=400
    assert page.evaluate("id=>!localStorage.getItem('roppo.chat.draft.'+id)&&!localStorage.getItem('roppo.resources.'+id)&&!localStorage.getItem('roppo.chat.panel.'+id)&&!sessionStorage.getItem('roppo.website.'+id)",f['chat'])
    page.reload();expect(page.get_by_text('个人记忆已恢复到初始状态。',exact=True)).to_be_visible()
    page.screenshot(path=str(root/'reset-completed.png'),full_page=True)
    check('confirmed reset clears personal contexts, learning and local drafts while retaining manual personality and all settings')
    assert not errors,errors
    browser.close()
(root/'evidence.json').write_text(json.dumps({'ok':True,'checks':checks,'errors':errors},ensure_ascii=False,indent=2))
