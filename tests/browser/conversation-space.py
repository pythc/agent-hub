"""Navigation layout regression on an isolated host; no model calls or config saves."""
import json, re, sys
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
from resource_helpers import open_resource

root, out = map(Path, sys.argv[1:3])
out.mkdir(parents=True, exist_ok=True)
info = json.loads((root / 'browser.json').read_text())
assert not info['native'], 'Use an isolated fixture'
base = info['base']
checks, errors, writes = [], [], []
with sync_playwright() as p:
    browser = p.chromium.launch()
    context = browser.new_context(viewport={'width': 1500, 'height': 960})
    name, value = info['cookie'].split('=', 1)
    context.add_cookies([{'name': name, 'value': value, 'url': base}])
    page = context.new_page()
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('request', lambda r: writes.append(r.url) if r.method != 'GET' else None)
    def button(name): return page.get_by_role('button', name=name, exact=True)
    def link(name): return page.get_by_role('link', name=name, exact=True)
    def shot(name): page.screenshot(path=str(out / (name + '.png')), animations='disabled')
    def bounded():
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth && document.documentElement.scrollHeight<=innerHeight')
    def settled_width(selector, value):
        page.wait_for_function('([selector,value])=>Math.abs(document.querySelector(selector).getBoundingClientRect().width-value)<1', arg=[selector, value])
    try:
        page.goto(base + '/chat')
        composer = page.get_by_role('textbox', name='Message Router', exact=True)
        expect(composer).to_be_visible()
        expect(page.locator('.session-panel')).to_have_count(0)
        settled_width('.functions-sidebar', 64)
        expect(page.locator('.conversation-sidebar')).to_be_visible()
        checks.append('first entry focuses the conversation with a collapsed feature rail and separate history')
        shot('collapsed-light')
        composer.fill('Keep this conversation draft')
        button('Expand function navigation').click()
        settled_width('.functions-sidebar', 208)
        expect(composer).to_have_value('Keep this conversation draft')
        shot('expanded-light')
        page.reload()
        settled_width('.functions-sidebar', 208)
        expect(composer).to_have_value('Keep this conversation draft')
        button('Collapse function navigation').click()
        button('Hide conversation list').click()
        expect(page.locator('.conversation-sidebar')).to_be_hidden()
        expect(button('Show conversation list')).to_be_focused()
        settled_width('.conversation-sidebar', 0)
        page.reload()
        expect(page.locator('.conversation-sidebar')).to_be_hidden()
        expect(composer).to_have_value('Keep this conversation draft')
        shot('conversation-focus-light')
        button('Show conversation list').click()
        expect(button('Hide conversation list')).to_be_focused()
        checks.append('feature and history preferences persist independently; focus and draft survive collapse/reload')
        page.evaluate('window.navigationBefore=document.querySelector(".functions-sidebar");window.documentMarker=crypto.randomUUID()')
        marker = page.evaluate('window.documentMarker')
        link('Agent team').click()
        expect(page.locator('#team-model')).to_be_visible()
        expect(page.locator('.conversation-sidebar')).to_be_hidden()
        assert page.evaluate('window.navigationBefore===document.querySelector(".functions-sidebar")')
        page.locator('#team-model').fill('local-unsaved-draft')
        link('Conversations').click()
        expect(composer).to_have_value('Keep this conversation draft')
        expect(page.locator('.conversation-sidebar')).to_be_visible()
        link('Agent team').click()
        expect(page.locator('#team-model')).to_have_value('local-unsaved-draft')
        button('Switch to dark mode').click()
        expect(page.locator('#team-model')).to_have_value('local-unsaved-draft')
        shot('management-dark')
        link('Conversations').click()
        button('Switch to Chinese').click()
        expect(button('展开功能栏')).to_be_visible()
        button('展开功能栏').click()
        expect(link('模型连接')).to_be_visible()
        shot('expanded-dark-zh')
        button('折叠功能栏').click()
        button('切换为英文').click()
        assert page.evaluate('window.documentMarker') == marker
        checks.append('one shared navigation DOM; management hides history and preserves both drafts, theme and language')
        button('Search conversations').click()
        search = page.get_by_role('textbox', name='Search conversations', exact=True)
        expect(search).to_be_focused()
        search.fill('no-such-conversation-2026')
        expect(page.locator('.thread-list .thread-item')).to_have_count(0)
        button('Search conversations').click()
        expect(search).to_have_count(0)
        button('Show archived conversations').click()
        button('Show recent conversations').click()
        checks.append('search and archive controls remain in the conversation space')
        conversations = page.request.get(base + '/api/chat/conversations').json()['conversations']
        original = next(c for c in conversations if c['title'])
        page.get_by_role('button', name=original['title'], exact=True).click()
        expect(composer).to_be_visible()
        settled_width('.functions-sidebar', 64)
        open_resource(page,'Team activity')
        expect(page.locator('.team-panel .worker-node')).to_have_count(2)
        expect(page.locator('.thread')).not_to_have_attribute('inert', '')
        shot('team-dark')
        open_resource(page,'Files')
        button('result.md').click()
        expect(page.locator('.file-preview')).to_contain_text('Two independent Worker browsers')
        shot('files-dark')
        page.set_viewport_size({'width': 1280, 'height': 900})
        button('Expand function navigation').click()
        expect(page.locator('.conversation-body')).to_have_class(re.compile('.*panel-overlay.*'))
        expect(page.locator('.thread')).to_have_attribute('inert', '')
        bounded()
        button('Hide conversation list').click()
        expect(page.locator('.conversation-body')).not_to_have_class(re.compile('.*panel-overlay.*'))
        expect(page.locator('.thread')).not_to_have_attribute('inert', '')
        button('Show conversation list').click()
        button('Collapse function navigation').click()
        open_resource(page,'Team activity')
        page.get_by_role('tab', name='Files', exact=True).focus()
        page.keyboard.press('End')
        expect(page.locator('.resource-tabs [role=tab]').last).to_be_focused()
        page.keyboard.press('Escape')
        expect(button('Session panel')).to_be_focused()
        checks.append('real file and Worker data; resource pane switches to overlay before it squeezes chat below 360px')
        for width in [820, 800, 390, 320]:
            page.set_viewport_size({'width': width, 'height': 844})
            page.emulate_media(reduced_motion='reduce')
            bounded()
            expect(composer).to_be_visible()
            if width <= 800:
                button('Open navigation').click()
                expect(link('Conversations')).to_be_focused()
                expect(page.locator('.chat-main')).to_have_attribute('inert', '')
                button('Expand function navigation').click()
                expect(page.locator('.conversation-sidebar')).to_be_hidden()
                expect(link('Model connections')).to_be_visible()
                bounded()
                if width == 390: shot('navigation-mobile-expanded-dark')
                button('Collapse function navigation').click()
                expect(page.locator('.conversation-sidebar')).to_be_visible()
                if width == 390: shot('navigation-mobile-dark')
                page.keyboard.press('Escape')
                expect(button('Open navigation')).to_be_focused()
            button('Session panel').click()
            expect(page.locator('.thread')).to_have_attribute('inert', '')
            bounded()
            if width == 390: shot('team-mobile-dark')
            button('Close panel').click()
            if width == 390: shot('conversation-mobile-dark')
        checks.append('820/800/390/320px: bounded viewport, drawer focus/Escape, mobile feature expansion and reduced motion')
        assert not errors, errors
        assert not writes, writes
        result = {'passed': True, 'checks': checks, 'pageErrors': errors, 'modelCalls': 0, 'configurationWrites': 0}
        (out / 'navigation-result.json').write_text(json.dumps(result, indent=2))
        print(json.dumps(result, indent=2))
    except Exception:
        shot('failure')
        raise
    finally:
        browser.close()
